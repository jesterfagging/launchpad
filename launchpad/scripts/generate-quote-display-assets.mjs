// Keep normal-page display identities independent of launch configuration data.
// Run after a launch catalogue change; --check verifies without writing files.
import { readFile, writeFile } from 'node:fs/promises';
import { LAUNCH_ASSETS } from '../public/launch-assets.mjs';
import { SOL_MINT, USDC_MINT } from '../public/launchpad-model.mjs';

const issuers = [...new Set(LAUNCH_ASSETS.map(asset => asset.issuer))];
const rows = LAUNCH_ASSETS.map(({ mint, name, symbol, issuer }) => [mint, name, symbol, issuers.indexOf(issuer)]);
const output = '// Generated by scripts/generate-quote-display-assets.mjs from the complete launch catalogue.\n' +
  '// Exact display identities only; launch eligibility and configuration stay in launch-assets.mjs.\n' +
  'const issuers = ' + JSON.stringify(issuers) + ';\n' +
  'const rows = [\n' + rows.map(row => JSON.stringify(row)).join(',\n') + '\n];\n' +
  'export const QUOTE_DISPLAY_ASSETS = rows.map(([mint, name, symbol, issuer]) => ({ mint, name, symbol, issuer: issuers[issuer] }));\n' +
  '// Exact native fallback records; the live API remains authoritative for all launch availability.\n' +
  'export const NATIVE_LAUNCH_ASSETS = ' + JSON.stringify(LAUNCH_ASSETS.filter(asset => [SOL_MINT, USDC_MINT].includes(asset.mint))) + ';\n';
const target = new URL('../public/quote-display-assets.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw Error('Quote display identities are stale. Run node scripts/generate-quote-display-assets.mjs.');
} else await writeFile(target, output);
console.log(`${rows.length} exact quote display identities ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
